/**
 * Единственное место, где розыгрыш случайности превращается в увод прицела.
 *
 * Отдельным модулем — потому что «неточность» в игре есть у двух разных источников:
 * у ствола (`WeaponDef.aimSpreadRad`) и у стрелка (`SMART_BOT_AIM_SPREAD_RAD`, скилл-модель
 * бота). Пока каждый считал увод сам, они разошлись в единицах: один делил конус пополам,
 * другой нет, и документация врала вдвое. Общая функция делает единицу одной по построению.
 *
 * Phaser-free: источник случайности остаётся в вызывающем, сюда приходит готовый розыгрыш.
 */

/**
 * Уводит `baseAngle` внутри конуса `coneRad` (**полный** угол от края до края) по
 * розыгрышу `roll` из `[-1, 1]`: -1 — левый край конуса, 0 — точно по прицелу, 1 — правый.
 *
 * Розыгрыш за пределами `[-1, 1]` обрезается, чтобы кривой генератор не расширял конус
 * за паспортный.
 */
export function jitterAngle(baseAngle: number, coneRad: number, roll: number): number {
  const clamped = Math.max(-1, Math.min(1, roll));
  return baseAngle + (clamped * coneRad) / 2;
}
