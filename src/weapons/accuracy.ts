/**
 * Phaser-free ядро оружия: неточность стрельбы.
 *
 * Неточность — не то же самое, что веер (`pellets.ts`): веер раскладывает дробинки одного
 * выстрела по детерминированным углам, а неточность случайно уводит выстрел целиком. Розыгрыш
 * приходит извне параметром, поэтому функция чистая и тестируемая; `Math.random` живёт в
 * оболочке (`Weapon`).
 */

/**
 * Отклоняет угол прицела внутри конуса `aimSpreadRad` (полный угол конуса).
 * `roll` — розыгрыш в диапазоне [-1, 1]; значения за пределами обрезаются, чтобы кривой
 * генератор не расширял конус за паспортный.
 */
export function jitterAngle(baseAngle: number, aimSpreadRad: number, roll: number): number {
  const clamped = Math.max(-1, Math.min(1, roll));
  return baseAngle + (clamped * aimSpreadRad) / 2;
}
